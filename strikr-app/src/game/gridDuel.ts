export function generateGrid(): DuelGrid {
  // A third of grids pit two triples of clubs against each other (a
  // player who turned out for both) instead of club x nationality — same
  // underlying cellCandidates()/matchesCriteria() logic already handles
  // 'club' criteria on both axes, this just needed a second precomputed
  // pool and a coin flip here to pick which kind to deal.
  if (Math.random() < 1 / 3) {
    const [rowClubs, colClubs] = VALID_GRIDS_CLUB_CLUB[Math.floor(Math.random() * VALID_GRIDS_CLUB_CLUB.length)];
    return {
      rows: rowClubs.map((value) => ({ type: 'club', value, label: value })),
      cols: colClubs.map((value) => ({ type: 'club', value, label: value })),
    };
  }
  const [clubValues, natValues] = VALID_GRIDS[Math.floor(Math.random() * VALID_GRIDS.length)];
  return {
    rows: clubValues.map((value) => ({ type: 'club', value, label: value })),
    cols: natValues.map((value) => ({ type: 'nat', value, label: NAT_FR[value] || value })),
  };
}

